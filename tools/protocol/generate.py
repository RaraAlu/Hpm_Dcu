def config_crc(data):
    crc = 0xFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = ((crc << 1) ^ (7 if crc & 0x80 else 0)) & 0xFF
    return crc


def sii(xml, settings):
    """Encode this product's CoE-only SII subset, not an arbitrary ESI compiler.

    Category layouts follow ETG.2010 (also documented in TI ecSlvApi_Eeprom.h).
    PDO names remain in ESI/CoE, not the bounded SII string table.
    """
    root = ET.fromstring(xml)
    devices = root.findall('./Descriptions/Devices/Device')
    if len(devices) != 1:
        raise ValueError('SII requires one device')
    device = devices[0]
    sms = device.findall('Sm')
    if [sm.text.strip() for sm in sms] != ['MBoxOut', 'MBoxIn', 'Outputs', 'Inputs']:
        raise ValueError('Unsupported SyncManager layout')
    mailbox = device.find('Mailbox')
    if [node.tag for node in mailbox] != ['CoE']:
        raise ValueError('Only the CoE mailbox is supported')
    coe = mailbox.find('CoE')
    modes = device.findall('./Dc/OpMode')
    activations = [number(mode.findtext('AssignActivate')) for mode in modes]
    if activations not in ([0x300], [0x300, 0]):
        raise ValueError('Expected DC Sync0 and optional SM2 synchronization')
    if len(modes) == 2 and any(node.tag.startswith(('CycleTime', 'ShiftTime')) for node in modes[1]):
        raise ValueError('SM2 synchronization must not specify a DC pulse')
    # Keep the boot SII category byte-identical. The extra mode is an ESI
    # selection for the master and does not change the on-board SII.
    mode = modes[0]
    cycle = mode.find('CycleTimeSync0')
    if (number(cycle.text) != 0 or number(cycle.get('Factor', '0')) != 1
            or mode.find('CycleTimeSync1') is not None):
        raise ValueError('DC Sync0 must use the master cycle; Sync1 is unsupported')
    size = number(device.findtext('./Eeprom/ByteSize'))
    if size != 16384:
        raise ValueError('DCU firmware requires a 16 KiB SII image')
    data = bytearray(128)
    config = bytes.fromhex(device.findtext('./Eeprom/ConfigData'))
    if len(config) != 10 or config[8:10] != b'\0\0':
        raise ValueError('Expected ten configuration bytes with an unassigned alias')
    data[:10] = config
    data[14] = config_crc(data[:14])
    identity = device.find('Type')
    struct.pack_into('<IIII', data, 16, number(root.findtext('./Vendor/Id')),
                     number(identity.get('ProductCode')), number(identity.get('RevisionNo')), 0)
    for i, sm in enumerate(sms[:2]):
        struct.pack_into('<HH', data, 48 + i * 4,
                         number(sm.get('StartAddress')), number(sm.get('DefaultSize')))
    struct.pack_into('<H', data, 56, 4)  # CoE.
    struct.pack_into('<HH', data, 124, size // 128 - 1, 1)

    strings = []

    def string(value):
        if value not in strings:
            strings.append(value)
        return strings.index(value) + 1

    group = string(device.findtext('GroupType'))
    product = string(settings['short_type'])
    name, desc = string(mode.findtext('Name')), string(mode.findtext('Desc'))
    encoded = [s.encode('ascii') for s in strings]
    if len(encoded) > 255 or any(len(s) > 255 for s in encoded):
        raise ValueError('SII strings must fit one-byte counts')
    string_data = bytes([len(encoded)]) + b''.join(bytes([len(s)]) + s for s in encoded)

    general = bytearray(32)
    general[:4] = bytes((group, 0, product, product))
    general[5] = 1 | sum((1 << bit) for bit, attr in enumerate(
        ('SdoInfo', 'PdoAssign', 'PdoConfig', 'PdoUpload', 'CompleteAccess'), 1)
        if coe.get(attr) in ('true', '1'))
    general[11] = settings['general_flags']
    if bool(general[11] & 8) != (device.findtext('./Info/IdentificationReg134') == 'true'):
        raise ValueError('General identification flags disagree with ESI')
    general[14] = group  # Secondary group index in the SSC category layout.
    physics = device.get('Physics')
    if len(physics) > 4 or any(port not in 'YH' for port in physics):
        raise ValueError('Unsupported physical port')
    ports = sum({'Y': 1, 'H': 4}[port] << (4 * i) for i, port in enumerate(physics))
    struct.pack_into('<H', general, 16, ports)

    fmmus = [node.text.strip() for node in device.findall('Fmmu')]
    if fmmus != ['Outputs', 'Inputs', 'MBoxState']:
        raise ValueError('Unsupported FMMU layout')
    fmmu = bytes((1, 2, 3, 0xFF))
    sm_data = b''
    regions = []
    for i, sm in enumerate(sms):
        start, length = number(sm.get('StartAddress')), number(sm.get('DefaultSize'))
        if not length or start < 0x1000 or start + length > 0x10000:
            raise ValueError('Invalid SyncManager memory region')
        if any(start < end and begin < start + length for begin, end in regions):
            raise ValueError('Overlapping SyncManager memory regions')
        regions.append((start, start + length))
        sm_data += struct.pack('<HHBBBB', start, length, number(sm.get('ControlByte')),
                               0, number(sm.get('Enable')), i + 1)

    def pdo_data(tag):
        encoded = bytearray()
        sm = 2 if tag == 'RxPdo' else 3
        assigned_bits = 0
        codes = {'INT': 3, 'DINT': 4, 'USINT': 5, 'UINT': 6, 'UDINT': 7, 'REAL': 8, 'ULINT': 27}
        for pdo in device.findall(tag):
            # Like the original SSC image, SII carries only the default profile.
            # Alternate assignments remain discoverable through ESI and CoE.
            if 'Sm' not in pdo.attrib:
                continue
            if number(pdo.get('Sm')) != sm:
                raise ValueError('PDO assigned to the wrong SyncManager')
            entries = pdo.findall('Entry')
            assigned_bits += sum(number(e.findtext('BitLen')) for e in entries)
            encoded += struct.pack('<HBBBBH', number(pdo.findtext('Index')), len(entries),
                                   number(pdo.get('Sm', '255')), 0, 0, 0)
            for entry in entries:
                encoded += struct.pack('<HBBBBH', number(entry.findtext('Index')),
                                       number(entry.findtext('SubIndex')), 0,
                                       codes[entry.findtext('DataType')], number(entry.findtext('BitLen')), 0)
        if assigned_bits != 8 * number(sms[sm].get('DefaultSize')):
            raise ValueError('PDO entries disagree with the default SyncManager length')
        return encoded

    dc = struct.pack('<IIIhHhBB4x', 0, number(mode.findtext('ShiftTimeSync0', '0')),
                     number(mode.findtext('ShiftTimeSync1', '0')), 0, 0x300, 1, name, desc)
    for kind, body in ((10, string_data), (30, general), (40, fmmu), (41, sm_data),
                       (50, pdo_data('TxPdo')), (51, pdo_data('RxPdo')), (60, dc)):
        body += b'\0' * (len(body) % 2)
        data += struct.pack('<HH', kind, len(body) // 2) + body
    if len(data) // 2 >= 4096 or len(data) + 2 > size:
        raise ValueError('SII categories exceed the IgH 4096-word boundary')
    data += b'\xFF' * (size - len(data))
    return bytes(data)


def eeprom_header(data):
    rows = [','.join(f'0x{value:02X}' for value in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
    return BANNER + '\r\nunsigned char aEepromData[] = {\r\n' + '\r\n'.join(rows) + '\r\n};\r\n'


def cyclic_contract(schema, pdos, profile):
    from generate_can_profile import profile_digest
    buses = sorted(c['bus'] for c in profile['channels'])
    counts = [0] * 4
    axes = {}
    for d in profile['devices']:
        bus = d['bus']
        slot = bus * 7 + counts[bus]
        counts[bus] += 1
        axes[slot] = {k: d[k] for k in ('id', 'protocol', 'type', 'model_profile_id', 'bus', 'can_id',
                                          'neutral_mit_only', 'zero_mit_loopback') if k in d}
    modes = []
    for mode, family in enumerate(schema['profiles']):
        image = {}
        for direction in ('rx', 'tx'):
            tx = direction == 'tx'
            refs, entries, length = [], [], 0
            for index in profile_indices(family, direction):
                p = pdos[index]
                base = 0x1A00 if tx else 0x1600
                ordinal = index - base
                if 1 <= ordinal <= 4 and ordinal - 1 not in buses: continue
                if 0x50 <= ordinal <= 0x53 and ordinal - 0x50 not in buses: continue
                if 0x20 <= ordinal < 0x3C:
                    device = axes.get(ordinal - 0x20)
                    if not device or (not tx and device['protocol'] == 'bjcx' and
                                      not device.get('neutral_mit_only')): continue
                if tx and ordinal == 0x40: continue  # No production IMU driver or Profile binding.
                offset = length
                for sub, field in enumerate(p['fields'], 1):
                    width = field_size(field)
                    entries.append(dict(index=p['index'], sub=sub, bits=width * 8, offset=length,
                                        type=field_type(field)[0], name=field['name'], meaning=field['label']))
                    length += width
                refs.append(dict(mapping=index, object=p['index'], offset=offset, bytes=length-offset,
                                 fields=len(p['fields'])))
            image[direction] = dict(bytes=length, blocks=refs, entries=entries)
        modes.append(image)
    result = dict(version=schema['constants']['MC_INTERFACE_VERSION'], channels=buses,
                  axes=[dict(slot=k, **axes[k]) for k in sorted(axes)], modes=modes)
    result['sha256'] = hashlib.sha256(json.dumps(result, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    result['profile_id'] = profile['startup']['profile_id']
    result['profile_revision'] = profile['startup']['revision']
    result['profile_sha256'] = profile_digest(profile).hex()
    return result


def rk_header(contract):
    loopback_mask = sum(1 << a['slot'] for a in contract['axes'] if a.get('zero_mit_loopback'))
    lines = [BANNER, '#ifndef DCU_PROFILE_PDO_HPP', '#define DCU_PROFILE_PDO_HPP', '#include <cstdint>',
             'namespace dcu_profile_pdo {',
             f"inline constexpr uint32_t interface_version = {contract['version']};",
             f"inline constexpr uint32_t profile_id = {contract['profile_id']}u, profile_revision = {contract['profile_revision']}u;",
             f"inline constexpr uint32_t channel_mask = {sum(1 << c for c in contract['channels'])}u, axis_mask = {sum(1 << a['slot'] for a in contract['axes'])}u;",
             f"inline constexpr uint32_t zero_mit_loopback_mask = {loopback_mask}u;",
             'struct Unit { const char *name; unsigned slot; };',
             'inline constexpr Unit units[] = {' +
             ''.join('{' + json.dumps(a['id']) + ',' + str(a['slot']) + '},' for a in contract['axes']) + '{nullptr,0}};',
             'struct Block { uint16_t mapping, object, offset, bytes, fields; };',
             'struct Image { const Block *blocks; const uint32_t *entries; unsigned count, bytes; };',
             'struct Mode { Image rx, tx; };',
             'inline constexpr uint8_t profile_digest[] = {' +
             ','.join(str(v) for v in bytes.fromhex(contract['profile_sha256'])) + '};',
             'inline constexpr uint8_t digest[] = {' +
             ','.join(str(v) for v in bytes.fromhex(contract['sha256'])) + '};']
    rows = []
    for n, mode in enumerate(contract['modes']):
        images = []
        for direction, image in mode.items():
            prefix = f'{direction}{n}'
            blocks = ','.join('{0x%(mapping)04x,0x%(object)04x,%(offset)d,%(bytes)d,%(fields)d}' % b for b in image['blocks'])
            words = ','.join(f"0x{e['index']:04x}{e['sub']:02x}{e['bits']:02x}u" for e in image['entries'])
            lines += [f'inline constexpr Block {prefix}_blocks[] = {{{blocks}}};',
                      f'inline constexpr uint32_t {prefix}_entries[] = {{{words}}};']
            images.append(f"{{{prefix}_blocks,{prefix}_entries,{len(image['blocks'])},{image['bytes']}}}")
        rows.append('{' + ','.join(images) + '}')
    lines.extend(['inline constexpr Mode modes[] = {' + ','.join(rows) + '};',
                  'constexpr int offset(const Image &im, unsigned object) {',
                  '    for (unsigned i = 0; i < im.count; ++i) if (im.blocks[i].object == object) return im.blocks[i].offset;',
                  '    return -1;', '}', '}', '#endif', ''])
    return '\n'.join(lines)


def outputs(schema_path=HERE / 'cfg/接口定义.json', template_path=HERE / 'cfg/设备模板.xml',
            profile_path=DEFAULT_CAN_PROFILE, allow_encos_fixture=False):
    from generate_can_profile import header as validate_profile, load_yaml
    schema = json.loads(schema_path.read_text(encoding='utf-8'))
    profile = load_yaml(profile_path)
    validate_profile(profile, allow_encos_fixture=allow_encos_fixture)
    objects, pdos = expand(schema)
    contract = cyclic_contract(schema, pdos, profile)
    default = contract['modes'][schema['default_profile']]
    assignments = {d: [b['mapping'] for b in image['blocks']] for d, image in default.items()}
    for i, p in pdos.items():
        p['default'] = i in assignments[p['direction']]
    xml = esi(template_path.read_bytes(), objects, pdos)
    binary = sii(xml, schema['sii'])
    return {
        'firmware/generated/encos/encos_interface.h': header(schema).encode(),
        'firmware/generated/encos/encos_storage.inc': storage(objects, contract['sha256']).encode(),
        'firmware/generated/ethercat/gatewayObjects.h': gateway(schema, objects, pdos, assignments).encode(),
        'firmware/generated/ethercat/digital_ioObjects.h': ssc_wrapper(schema).encode(),
        'protocol/ethercat/HPM_ENCOS_4CAN_28AXIS_IMU.xml': xml,
        'protocol/ethercat/HPM_ENCOS_4CAN_28AXIS_IMU.bin': binary,
        'firmware/generated/ethercat/eeprom.h': eeprom_header(binary).encode(),
        'protocol/ethercat/dcu_profile_pdo.hpp': rk_header(contract).encode(),
        'protocol/ethercat/周期布局.json': (json.dumps(contract, ensure_ascii=False, indent=2) + '\n').encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-root', type=Path, help='Generate into this directory; default is read-only check')
    parser.add_argument('--profile', type=Path, default=DEFAULT_CAN_PROFILE)
    parser.add_argument('--allow-encos-fixture', action='store_true')
    arguments = parser.parse_args()
    mismatches = []
    for relative, content in outputs(profile_path=arguments.profile, allow_encos_fixture=arguments.allow_encos_fixture).items():
        target = (arguments.output_root or ROOT) / relative
        if arguments.output_root:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        elif not target.exists() or target.read_bytes() != content:
            mismatches.append(relative)
    if mismatches:
        print('Generated files differ:\n' + '\n'.join(mismatches), file=sys.stderr)
        return 1
    print('Protocol generation ' + ('written' if arguments.output_root else 'verified'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
