#!/usr/bin/env python3
"""Generate the isolated single-channel profile, never the production ABI."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

from check_gateway_contract import identifier, keys, load_yaml, require, uint


def bounded(value, low, high, where):
    uint(value, 32, where, low)
    require(value <= high, f"{where}: exceeds {high:#x}")
    return value


def single(items, where):
    require(type(items) is list and len(items) == 1, f"{where}: expected exactly one entry")
    return items[0]


def validate(profile):
    expected = {"schema_version", "channels", "pdo", "frame_timeout_ms"}
    if type(profile) is dict and "session" in profile:
        expected.add("session")
    keys(profile, expected, "profile")
    require(type(profile["schema_version"]) is int and profile["schema_version"] == 1,
            "unsupported static profile schema")
    channel = single(profile["channels"], "channels")
    keys(channel, {"bus", "mode", "nominal_bitrate_kbps", "devices"}, "channel")
    require(channel["mode"] == "classic", "only classic CAN is supported")
    bus = bounded(channel["bus"], 0, 3, "channel.bus")
    require(type(channel["nominal_bitrate_kbps"]) is int and channel["nominal_bitrate_kbps"] == 1000,
            "nominal_bitrate_kbps: isolated profile requires 1000")
    device = single(channel["devices"], "devices")
    keys(device, {"id", "protocol", "can_id_base"}, "device")
    identifier(device["id"], "device.id")
    require(device["protocol"] == "internal_echo_v1", "only the isolated internal echo is supported")

    pdo = profile["pdo"]
    keys(pdo, {"rx", "tx"}, "pdo")
    rx, tx = pdo["rx"], pdo["tx"]
    keys(rx, {"mapping", "object", "words"}, "pdo.rx")
    keys(tx, {"mapping", "object"}, "pdo.tx")
    # One classic CAN frame holds two 32-bit PDO words; Tx appends four status words.
    words = bounded(rx["words"], 2, 8, "pdo.rx.words")
    require(words % 2 == 0, "pdo.rx.words: must contain whole classic CAN frames")
    frames = words // 2
    can_id = bounded(device["can_id_base"], 0, 0x800 - frames, "device.can_id_base")
    result = {
        "CAN_BUS": bus,
        "CAN_BITRATE_KBPS": channel["nominal_bitrate_kbps"],
        "CAN_ID_BASE": hex(can_id),
        "CAN_FRAMES": frames,
        "FRAME_TIMEOUT_MS": bounded(profile["frame_timeout_ms"], 1, 20, "frame_timeout_ms"),
        "RX_WORDS": words,
        "TX_WORDS": words + 4,
        "RX_MAP": hex(bounded(rx["mapping"], 0x1600, 0x17ff, "pdo.rx.mapping")),
        "TX_MAP": hex(bounded(tx["mapping"], 0x1a00, 0x1bff, "pdo.tx.mapping")),
        "RX_OBJECT": hex(bounded(rx["object"], 0x7000, 0x7fff, "pdo.rx.object")),
        "TX_OBJECT": hex(bounded(tx["object"], 0x6000, 0x6fff, "pdo.tx.object")),
        "DEVICE_ID": device["id"],
    }
    if "session" in profile:
        session = profile["session"]
        fields = {"profile_id", "revision", "probe_interval_ms", "readiness_ttl_ms",
                  "activation_wait_s", "command_timeout_ms"}
        keys(session, fields, "session")
        for field in fields:
            uint(session[field], 32, f"session.{field}", 1)
        require(words >= 4, "session requires room for the session ID, sequence and payload")
        exchange_ms = frames * result["FRAME_TIMEOUT_MS"]
        require(session["probe_interval_ms"] + exchange_ms < session["readiness_ttl_ms"] and
                session["readiness_ttl_ms"] < session["activation_wait_s"] * 1000 and
                exchange_ms < session["command_timeout_ms"], "session deadlines do not cover the echo budget")
        for field in sorted(fields):
            result[field.upper()] = session[field]
    return result


def header(profile, require_session=False):
    values = validate(profile)
    require(not require_session or "PROFILE_ID" in values, "session preset requires the session block")
    lines = ["/* Generated by generate_static_profile.py; do not edit. */",
             "#ifndef DCU_STATIC_PROFILE_GENERATED_H", "#define DCU_STATIC_PROFILE_GENERATED_H", ""]
    for key, value in values.items():
        literal = f'"{value}"' if key == "DEVICE_ID" else f"{value}U"
        lines.append(f"#define DCU_PROFILE_{key} {literal}")
    for direction in ("RX", "TX"):
        entries = " ".join(f"X({n})" for n in range(1, values[f"{direction}_WORDS"] + 1))
        lines.append(f"#define DCU_PROFILE_{direction}_ENTRIES(X) {entries}")
    if "PROFILE_ID" in values:
        normalized = json.dumps({"schema_version": 1, "session_layout": 2, **values},
                                sort_keys=True, separators=(",", ":")).encode("ascii")
        digest = ", ".join(f"0x{byte:02x}U" for byte in hashlib.sha256(normalized).digest())
        lines.append(f"#define DCU_PROFILE_DIGEST {{ {digest} }}")
    return "\n".join([*lines, "", "#endif", ""])


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--require-session", action="store_true")
    args = parser.parse_args(argv)
    try:
        generated = header(load_yaml(args.profile), args.require_session)
        args.output.write_text(generated, encoding="ascii")
    except (OSError, ValueError) as error:
        print(f"Static profile: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
