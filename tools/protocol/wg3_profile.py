"""WG3 device declarations for the shared firmware / EtherCAT generator."""

import json

from profile_yaml import keys, require


def profile_from_wg3(root):
    policy = root["mcu"]
    keys(policy, {"startup", "safety", "motor_bus", "head_bus", "motor", "bjcx", "head"}, "mcu")
    keys(policy["motor"], {"motion_parameters"}, "motor policy")
    keys(policy["bjcx"], {"status_poll_period_ms", "status_reply_timeout_ms"}, "bjcx policy")
    keys(policy["head"], {"heartbeat_timeout_ms", "feedback_periods", "service_frames"}, "head policy")
    channels, devices = [], []
    for bus in root["wg3"]:
        number = bus["channel"]
        if "motor" in bus:
            keys(bus, {"channel", "motor"}, "motor channel")
            require(isinstance(bus["motor"], list) and bus["motor"], "expected motor devices")
            channels.append(dict(policy["motor_bus"], bus=number))
            for item in bus["motor"]:
                keys(item, {"name", "id", "brand", "type"}, "motor")
                device = dict(policy["motor"], id=f"can_{number}_{item['id']}", bus=number,
                              can_id=item["id"], protocol=item["brand"], type=item["type"])
                if item["brand"] == "bjcx":
                    device.update(policy["bjcx"])
                devices.append(device)
        else:
            keys(bus, {"channel", "head"}, "head channel")
            # USTC head v2 has five ordered eight-byte pose groups.
            require(isinstance(bus["head"], list) and len(bus["head"]) == 5, "head requires five pose groups")
            frames = {}
            for i, frame in enumerate(bus["head"], 1):
                keys(frame, {"id"}, "head frame")
                frames[f"head_{i}"] = {"can_id": frame["id"], "dlc": 8}
            side = {"period_us": root["pdo"]["period_us"], "frames": frames,
                    "slots": ["head_1", "left_hand", "head_2", "right_hand", "head_3", "idle",
                              "head_4", "idle", "head_5", "idle"],
                    "ustc_head_v2": {k: policy["head"][k] for k in ("heartbeat_timeout_ms", "feedback_periods")},
                    "service_frames": policy["head"]["service_frames"]}
            channels.append(dict(policy["head_bus"], bus=number, cyclic_sideband=side))
    return {"schema_version": 3, "startup": policy["startup"], "safety": policy["safety"],
            "channels": channels, "devices": devices}


def device_header(profile, contract, schema, policy):
    """Typed host view; offsets come from the very same image exported to the slave."""
    mode = contract["modes"][1]
    tx = {b["object"]: b for b in mode["tx"]["blocks"]}
    rx = {b["object"]: b for b in mode["rx"]["blocks"]}
    by_id = {a["id"]: a for a in contract["axes"]}
    motors = profile["devices"]
    lines = ["// Generated by the DCU protocol generator; do not edit.", "#pragma once",
             "#include <array>", "#include <cstdint>", "#include <cstring>", "#include <string_view>",
             '#include <dcu_sideband.hpp>', '#include <drivers/encos/cfg/encos_models.h>',
             '#include <drivers/bjcx/cfg/bjcx_models.h>', "namespace dcu_profile_pdo::device {",
             "#pragma pack(push, 1)"]
    for tag, ctype in (("BoardFeedback", "mc_board_tx_t"), ("MotorFeedback", "mc_axis_tx_t"),
                       ("BoardCommand", "mc_board_rx_t"), ("ChannelCommand", "mc_channel_rx_t")):
        lines.append(f"struct {tag} {{")
        for f in schema["types"][ctype]:
            lines.append(f"  {f['type']} {f['name']};")
        lines.append("};")
    lines += ["#pragma pack(pop)", "struct Motor { unsigned bus, can_id; std::string_view brand, model; };",
              f"inline constexpr std::array<Motor, {len(motors)}> motors = {{{{"]
    for d in motors:
        lines.append(f'  {{{d["bus"]}, {d["can_id"]}, {json.dumps(d["protocol"])}, {json.dumps(str(d["type"]))}}},')
    feedback = [tx[0x6200 + by_id[d["id"]]["slot"]] for d in motors]
    for b in feedback:
        require(b["bytes"] == tx[0x6200 + by_id[motors[0]["id"]]["slot"]]["bytes"], "mixed motor feedback ABI")
    side = contract.get("cyclic_sideband", {})
    groups = [v["can_id"] for k, v in side.get("frames", {}).items() if k.startswith("head_")]
    def array(name, values):
        return (f"inline constexpr std::array<unsigned, {len(values)}> {name} = {{" +
                ", ".join(map(str, values)) + "};")
    lines += ["}};"]
    for brand, model in sorted({(d["protocol"], str(d["type"])) for d in motors}):
        lines.append(f'static_assert(dcu::motor::{brand}_config::find_model({json.dumps(model)}) != nullptr, '
                     f'"Unknown {brand} model: {model}");')
    lines += [array("head_ids", groups),
              'inline constexpr char mcu_policy[] = R"json(' + json.dumps(policy, sort_keys=True) + ')json";',
              "namespace detail {",
              array("feedback_offsets", [b["offset"] for b in feedback]),
              array("fault_bits", [1 << by_id[d["id"]]["slot"] for d in motors]),
              f"static_assert(sizeof(BoardCommand) == {rx[0x7000]['bytes']});",
              f"static_assert(sizeof(BoardFeedback) == {tx[0x6000]['bytes']});"]
    if feedback:
        lines.append(f"static_assert(sizeof(MotorFeedback) == {feedback[0]['bytes']});")
    if side:
        channel = rx[0x7100 + side["bus"]]
        lines.append(f"static_assert(sizeof(ChannelCommand) == {channel['bytes']});")
    lines += ["}", f"using Input = std::array<uint8_t, {mode['tx']['bytes']}>;",
              f"using Output = std::array<uint8_t, {mode['rx']['bytes']}>;",
              "inline BoardFeedback board(const Input &in) { BoardFeedback v; std::memcpy(&v, in.data(), sizeof(v)); return v; }",
              "inline MotorFeedback feedback(const Input &in, unsigned i) { MotorFeedback v;",
              "  std::memcpy(&v, in.data() + detail::feedback_offsets.at(i), sizeof(v)); return v; }",
              "inline bool fault(const BoardFeedback &b, unsigned i) { return b.AxisFaultMask & detail::fault_bits.at(i); }",
              "inline bool device_faults(const BoardFeedback &b) { return (b.AxisFaultMask & axis_mask) || (b.ChannelFaultMask & channel_mask); }",
              "inline void begin(Output &out, const BoardCommand &b) { out.fill(0); std::memcpy(out.data(), &b, sizeof(b)); }",
              "inline constexpr unsigned head_periods = sideband_slots.size();",
              "constexpr int head_frame(unsigned phase) { const auto &s = sideband_slots.at(phase); return s.bound ? s.frame.can_id : -1; }",
              "inline void head(Output &out, const ChannelCommand &c) {"]
    if side:
        tail = rx[0x7300]
        lines.append(f"  std::memcpy(out.data() + {channel['offset']}, &c, sizeof(c));")
    lines += ["}", "inline bool head_payload(Output &out, unsigned phase, const uint8_t *payload, unsigned n) {"]
    if side:
        lines.append(f"  return write_sideband_slot(out.data() + {tail['offset']}, {tail['bytes']}, phase, payload, n);")
    else:
        lines.append("  return false;")
    lines.extend(["}", "}", ""])
    return "\n".join(lines)
