#define DCU_DATA_SM0_CTRL 0x26U
#define DCU_DATA_SM1_CTRL 0x22U
#define DCU_DATA_SM2_CTRL 0x64U
#define DCU_DATA_SM3_CTRL 0x20U

#define DCU_DATA_LE16(v) ((v) & 0xffU), (((v) >> 8) & 0xffU)
#define DCU_DATA_LE32(v) DCU_DATA_LE16(v), DCU_DATA_LE16((v) >> 16)

#endif
