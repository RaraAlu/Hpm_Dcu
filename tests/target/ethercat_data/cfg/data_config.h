#define DCU_DATA_RX_BYTES (4U * DCU_DATA_RX_WORDS)
#define DCU_DATA_TX_BYTES (4U * DCU_DATA_TX_WORDS)
#define DCU_DATA_RX_WORDS 8U
#define DCU_DATA_TX_WORDS 12U
