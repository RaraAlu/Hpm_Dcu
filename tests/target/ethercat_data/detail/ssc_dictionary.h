#ifndef DCU_DATA_SSC_DICTIONARY_H
#define DCU_DATA_SSC_DICTIONARY_H

#define DCU_DATA_COUNT_DESC {DEFTYPE_UNSIGNED8, 8, ACCESS_READ}
#define DCU_DATA_U16_DESC {DEFTYPE_UNSIGNED16, 16, ACCESS_READ}
#define DCU_DATA_MAP_DESC(n) {DEFTYPE_UNSIGNED32, 32, ACCESS_READ},
#define DCU_DATA_RX_DESC(n) {DEFTYPE_UNSIGNED32, 32, ACCESS_READ | OBJACCESS_RXPDOMAPPING},
#define DCU_DATA_TX_DESC(n) {DEFTYPE_UNSIGNED32, 32, ACCESS_READ | OBJACCESS_TXPDOMAPPING},
#define DCU_DATA_MAP_WORDS(n, object) (((n) << 8) | 32), object,
#define DCU_DATA_RX_MAP_WORDS(n) DCU_DATA_MAP_WORDS(n, DCU_DATA_RX_OBJECT)
#define DCU_DATA_TX_MAP_WORDS(n) DCU_DATA_MAP_WORDS(n, DCU_DATA_TX_OBJECT)
#define DCU_DATA_OD(index, type, count, code, desc, name, value, read) \
    {NULL, NULL, index, {type, (count) | ((code) << 8)}, desc, name, value, read, NULL, 0}

#endif
